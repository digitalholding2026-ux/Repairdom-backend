/**
 * Codes valides, en majuscules.
 *
 * Construit depuis `NATIONALITIES` plutôt qu'écrit à la main : impossible que la
 * validation backend et le sélecteur frontend divergent sur la liste.
 */
export const NATIONALITY_CODES: ReadonlySet<string> = new Set(
  NATIONALITIES.map((entry) => entry.code),
);

/** Libellé français d'un code alpha-2, ou `undefined` si code inconnu. */
export function nationalityLabel(code: string | null | undefined): string | undefined {
  if (!code) return undefined;
  return NATIONALITIES.find((entry) => entry.code === code.toUpperCase())?.label;
}

/**
 * Normalise une nationalité en code ISO 3166-1 alpha-2 majuscule, ou `null`
 * si la valeur n'est pas un code alpha-2.
 *
 * NORMALISE SEULEMENT la casse et les espaces : la validation d'EXISTENCE du
 * code est faite par l'appelant via `isKnownNationalityCode`. Cette
 * fonction ne valide donc volontairement pas `ZZ` — le service lève ensuite
 * une erreur applicative avec le bon message.
 */
export function normalizeNationality(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const code = value.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) return null;
  return code;
}